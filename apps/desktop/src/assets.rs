pub fn reaction_asset_path(id: &str) -> Option<String> {
    let path = format!("reactions/{}.png", id.to_ascii_lowercase());
    ASSETS.iter().any(|(name, _)| *name == path).then_some(path)
}

impl AssetSource for Assets {
    fn load(&self, path: &str) -> anyhow::Result<Option<Cow<'static, [u8]>>> {
        let local = ASSETS
            .iter()
            .find(|(name, _)| *name == path)
            .map(|(_, bytes)| Cow::Borrowed(*bytes));
        if local.is_some() {
            return Ok(local);
        }
        gpui_component_assets::Assets.load(path)
    }

    fn list(&self, path: &str) -> anyhow::Result<Vec<SharedString>> {
        let mut assets = ASSETS
            .iter()
            .filter(|(name, _)| name.starts_with(path))
            .map(|(name, _)| SharedString::from(*name))
            .collect::<Vec<_>>();
        assets.extend(gpui_component_assets::Assets.list(path)?);
        Ok(assets)
    }
}

pub fn register_fonts(cx: &gpui::App) -> anyhow::Result<()> {
    cx.text_system().add_fonts(vec![
        Cow::Borrowed(include_bytes!("../assets/fonts/JetBrainsMono-Regular.ttf").as_slice()),
        Cow::Borrowed(include_bytes!("../assets/fonts/JetBrainsMono-Bold.ttf").as_slice()),
    ])?;
    Ok(())
}
